-- SiloMath PostgreSQL migration test
-- Assertions executed AFTER SiloMath V6 migrations.
--
-- Verifies:
--   * representative legacy business data survived;
--   * Campaign was canonicalized without semantic loss;
--   * Scope survived;
--   * Team assignment survived;
--   * legacy launch snapshot survived;
--   * missing historical calculation/schema provenance was NOT fabricated;
--   * controlled NEEDS_PROVENANCE staging exists exactly once.

do $$
declare
    v_org_id uuid := '11111111-1111-1111-1111-111111111111';
    v_user_id uuid := '22222222-2222-2222-2222-222222222222';
    v_space_id uuid := '55555555-5555-5555-5555-555555555555';

    v_campaign_id uuid;
    v_legacy_snapshot_id uuid;

    campaign_count integer;
    scope_count integer;
    team_count integer;
    provenance_count integer;
    canonical_snapshot_count integer;

    v_type text;
    v_status text;
    v_code text;
    v_name text;
    v_start_date date;
    v_planned_end_date date;
begin
    --------------------------------------------------------------------
    -- RESOLVE THE CAMPAIGN GENERATED BY THE LEGACY RPC
    --------------------------------------------------------------------

    select
        c.campaign_id,
        c.inventory_type,
        c.status,
        c.code,
        c.name,
        c.start_date,
        c.planned_end_date
    into
        v_campaign_id,
        v_type,
        v_status,
        v_code,
        v_name,
        v_start_date,
        v_planned_end_date
    from silomath.inventory_campaigns c
    where c.organization_id = v_org_id
      and c.code = 'INV-2026-0001';

    if v_campaign_id is null then
        raise exception
            'ASSERTION FAILED: canonical migrated Campaign was not found';
    end if;

    --------------------------------------------------------------------
    -- CANONICAL CAMPAIGN
    --------------------------------------------------------------------

    select count(*)
    into campaign_count
    from silomath.inventory_campaigns
    where campaign_id = v_campaign_id;

    if campaign_count <> 1 then
        raise exception
            'ASSERTION FAILED: canonical campaign count %, expected 1',
            campaign_count;
    end if;

    if v_type <> 'ANNUAL' then
        raise exception
            'ASSERTION FAILED: inventory_type %, expected ANNUAL',
            v_type;
    end if;

    if v_status <> 'ACTIVE' then
        raise exception
            'ASSERTION FAILED: status %, expected ACTIVE',
            v_status;
    end if;

    if v_code <> 'INV-2026-0001' then
        raise exception
            'ASSERTION FAILED: code %, expected INV-2026-0001',
            v_code;
    end if;

    if v_name <> 'Migration Fixture Campaign' then
        raise exception
            'ASSERTION FAILED: campaign name was not preserved';
    end if;

    if v_start_date <> date '2026-10-01' then
        raise exception
            'ASSERTION FAILED: Start Date % was not preserved',
            v_start_date;
    end if;

    if v_planned_end_date <> date '2026-10-31' then
        raise exception
            'ASSERTION FAILED: Planned End Date % was not preserved',
            v_planned_end_date;
    end if;

    --------------------------------------------------------------------
    -- CANONICAL SCOPE
    --------------------------------------------------------------------

    select count(*)
    into scope_count
    from silomath.campaign_scopes
    where campaign_id = v_campaign_id
      and storage_space_id = v_space_id;

    if scope_count <> 1 then
        raise exception
            'ASSERTION FAILED: canonical scope count %, expected 1',
            scope_count;
    end if;

    --------------------------------------------------------------------
    -- CANONICAL TEAM
    --------------------------------------------------------------------

    select count(*)
    into team_count
    from silomath.campaign_team_assignments
    where campaign_id = v_campaign_id
      and user_id = v_user_id
      and status = 'ACTIVE';

    if team_count <> 1 then
        raise exception
            'ASSERTION FAILED: canonical active team count %, expected 1',
            team_count;
    end if;

    --------------------------------------------------------------------
    -- LEGACY SOURCE MUST STILL EXIST
    --------------------------------------------------------------------

    if not exists (
        select 1
        from public.campaigns legacy
        where legacy.id = v_campaign_id
          and legacy.organization_id = v_org_id
          and legacy.code = 'INV-2026-0001'
          and legacy.name = 'Migration Fixture Campaign'
          and legacy.inventory_type = 'Annual'
          and legacy.status = 'Active'
    ) then
        raise exception
            'ASSERTION FAILED: legacy Campaign source data was lost or rewritten';
    end if;

    select legacy.launch_snapshot_id
    into v_legacy_snapshot_id
    from public.campaigns legacy
    where legacy.id = v_campaign_id;

    if v_legacy_snapshot_id is null then
        raise exception
            'ASSERTION FAILED: legacy launch snapshot reference was lost';
    end if;

    if not exists (
        select 1
        from public.campaign_launch_snapshots cls
        where cls.id = v_legacy_snapshot_id
          and cls.campaign_id = v_campaign_id
    ) then
        raise exception
            'ASSERTION FAILED: legacy Campaign launch snapshot was lost';
    end if;

    if not exists (
        select 1
        from public.campaign_launch_snapshot_items item
        where item.snapshot_id = v_legacy_snapshot_id
          and item.storage_space_id = v_space_id
    ) then
        raise exception
            'ASSERTION FAILED: legacy Campaign launch snapshot item was lost';
    end if;

    if not exists (
        select 1
        from public.campaign_launch_team_snapshot team_item
        where team_item.snapshot_id = v_legacy_snapshot_id
          and team_item.user_id = v_user_id
    ) then
        raise exception
            'ASSERTION FAILED: legacy Campaign launch team snapshot was lost';
    end if;

    --------------------------------------------------------------------
    -- CONTROLLED SNAPSHOT PROVENANCE GAP
    --
    -- Legacy launch snapshots do not contain the authoritative V6
    -- calculation/schema compatibility identifiers.
    --
    -- Migration MUST stage the record as NEEDS_PROVENANCE rather than
    -- fabricate current or guessed version values.
    --------------------------------------------------------------------

    select count(*)
    into provenance_count
    from silomath.legacy_campaign_snapshot_provenance provenance
    where provenance.legacy_snapshot_id = v_legacy_snapshot_id
      and provenance.legacy_campaign_id = v_campaign_id
      and provenance.migration_status = 'NEEDS_PROVENANCE'
      and provenance.snapshot_schema_version is null
      and provenance.engine_version is null
      and provenance.input_schema_version is null
      and provenance.normalization_version is null
      and provenance.surface_model_version is null
      and provenance.aggregation_method is null
      and provenance.aggregation_rule_version is null;

    if provenance_count <> 1 then
        raise exception
            'ASSERTION FAILED: expected exactly one controlled NEEDS_PROVENANCE row, found %',
            provenance_count;
    end if;

    --------------------------------------------------------------------
    -- CANONICAL SNAPSHOT MUST NOT BE FABRICATED YET
    --------------------------------------------------------------------

    select count(*)
    into canonical_snapshot_count
    from silomath.campaign_snapshots snapshot
    where snapshot.campaign_id = v_campaign_id;

    if canonical_snapshot_count <> 0 then
        raise exception
            'ASSERTION FAILED: canonical CampaignSnapshot was fabricated without authoritative provenance';
    end if;

    if exists (
        select 1
        from silomath.inventory_campaigns campaign
        where campaign.campaign_id = v_campaign_id
          and campaign.campaign_snapshot_id is not null
    ) then
        raise exception
            'ASSERTION FAILED: canonical Campaign was linked to a fabricated snapshot';
    end if;

    --------------------------------------------------------------------
    -- CANONICAL FOUNDATION TABLE INVENTORY
    --------------------------------------------------------------------

    if to_regclass('silomath.users') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.users does not exist';
    end if;

    if to_regclass('silomath.organizations') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.organizations does not exist';
    end if;

    if to_regclass('silomath.organization_memberships') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.organization_memberships does not exist';
    end if;

    if to_regclass('silomath.device_installations') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.device_installations does not exist';
    end if;

    if to_regclass('silomath.locations') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.locations does not exist';
    end if;

    if to_regclass('silomath.clients') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.clients does not exist';
    end if;
    if to_regclass('silomath.storage_units') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.storage_units does not exist';
    end if;

    if to_regclass('silomath.geometry_families') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.geometry_families does not exist';
    end if;

    if to_regclass('silomath.geometry_profiles') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.geometry_profiles does not exist';
    end if;
    if to_regclass('silomath.storage_spaces') is null then
        raise exception
            'ASSERTION FAILED: canonical foundation table silomath.storage_spaces does not exist';
    end if;
    if to_regclass('silomath.geometry_profile_versions') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.geometry_profile_versions does not exist';
    end if;
    if to_regclass('silomath.commodities') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.commodities does not exist';
    end if;

    if to_regclass('silomath.commodity_versions') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.commodity_versions does not exist';
    end if;
    if to_regclass('silomath.campaign_snapshot_scope_items') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.campaign_snapshot_scope_items does not exist';
    end if;

    if to_regclass('silomath.campaign_snapshot_team_items') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.campaign_snapshot_team_items does not exist';
    end if;
    if to_regclass('silomath.offline_working_set_manifests') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.offline_working_set_manifests does not exist';
    end if;
    if to_regclass('silomath.stocktaking_records') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.stocktaking_records does not exist';
    end if;

    if to_regclass('silomath.stocktaking_revisions') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.stocktaking_revisions does not exist';
    end if;
    if to_regclass('silomath.measurements') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.measurements does not exist';
    end if;
    if to_regclass('silomath.calculation_results') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.calculation_results does not exist';
    end if;
    if to_regclass('silomath.issues') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.issues does not exist';
    end if;

    if to_regclass('silomath.issue_resolutions') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.issue_resolutions does not exist';
    end if;

    if to_regclass('silomath.issue_status_events') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.issue_status_events does not exist';
    end if;
    if to_regclass('silomath.evidence') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.evidence does not exist';
    end if;
    if to_regclass('silomath.final_inventory_snapshots') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.final_inventory_snapshots does not exist';
    end if;

    if to_regclass('silomath.final_inventory_snapshot_entries') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.final_inventory_snapshot_entries does not exist';
    end if;
    if to_regclass('silomath.audit_events') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.audit_events does not exist';
    end if;
    if to_regclass('silomath.notifications') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.notifications does not exist';
    end if;
    if to_regclass('silomath.user_preferences') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.user_preferences does not exist';
    end if;
    if to_regclass('silomath.organization_configurations') is null then
        raise exception
            'ASSERTION FAILED: canonical table silomath.organization_configurations does not exist';
    end if;
    raise notice
        'V6 MIGRATION ASSERTIONS PASSED: campaign_id=%, legacy_snapshot_id=%',
        v_campaign_id,
        v_legacy_snapshot_id;
end;
$$;
